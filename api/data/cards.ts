export const minorArcana = suits.flatMap((suit) => {
  const cards = [];
  
  for (const num of numberCards) {
    const meanings = numberMeanings[suit][num.toString()];
    cards.push({
      name: `${num} of ${suitNames[suit].name}`,
      type: 'minor',
      suit,
      number: num,
      meaningUpright: meanings.upright,
      meaningReversed: meanings.reversed,
      keywords: meanings.keywords,
    });
  }
  
  for (const court of courtCards) {
    const meanings = courtMeanings[court];
    cards.push({
      name: `${court} of ${suitNames[suit].name}`,
      type: 'minor',
      suit,
      meaningUpright: meanings.upright,
      meaningReversed: meanings.reversed,
      keywords: meanings.keywords,
    });
  }
  
  return cards;
});

export const allCards = [...majorArcana, ...minorArcana];
